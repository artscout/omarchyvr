// Golden joint sets: pimax-hands (Rust) curls -> Monado u_hand_sim_simulate_generic (C), exactly the driver path.
// Build (from a configured+built Monado tree, B=build dir, S=source dir, T=cargo target dir):
//   cc -D_GNU_SOURCE -I$S/src/xrt/auxiliary -I$B/src/xrt/auxiliary -I$S/src/xrt/include -I$B/src/xrt/include \
//      -I<pimax-re>/rust/pimax-hands/include -O1 -o golden gen_golden.c $B/src/xrt/auxiliary/util/libaux_util.a \
//      $B/src/xrt/auxiliary/math/libaux_math.a $B/src/xrt/auxiliary/util/libaux_util.a $T/release/libpimax_hands.a \
//      -lm -lpthread -ldl -lgcc_s -lrt -lutil && ./golden > hand_joints.txt  (then re-add the # header of hand_joints.txt)
// Output format (text, one block per case and hand):
//   case <name> <L|R> in trigger=<f> grip=<f> flags=<u> curls l r m i t = <5 floats> thumb_state=<u>
//   26 lines: x y z qx qy qz qw   (wrist frame, OpenXR joint order PALM, WRIST, THUMB[4], INDEX[5], MIDDLE[5], RING[5], LITTLE[5])
#include <stdio.h>
#include <string.h>
#include "xrt/xrt_defines.h"
#include "util/u_hand_simulation.h"
#include "util/u_hand_tracking.h"
#include "pimax_hands.h"

struct kase { const char *name; float trigger, grip; unsigned flags; };

static void to_values(const pimax_hands_out *o, struct u_hand_tracking_values *v)
{
	const pimax_hands_finger *src[5] = {&o->little, &o->ring, &o->middle, &o->index, &o->thumb};
	struct u_hand_tracking_finger_value *dst[5] = {&v->little, &v->ring, &v->middle, &v->index, &v->thumb};
	for (int f = 0; f < 5; f++) {
		dst[f]->splay = src[f]->splay;
		for (int j = 0; j < 4; j++) dst[f]->joint_curls[j] = src[f]->joint_curls[j];
		dst[f]->joint_count = 4;
	}
}

int main(void)
{
	// Steady-state inputs. Trigger/grip chosen so every normalised curl is exactly reachable:
	// index curl = 0.10 + 0.75 * shape(trigger), lower = 0.25 + 0.75 * shape(grip)  (deadzone 0.02).
	struct kase cases[] = {
	    {"rest", 0.0f, 0.0f, 0},
	    {"trigger_full", 1.0f, 0.0f, 0},
	    {"grip_full", 0.0f, 1.0f, 0},
	    {"fist", 1.0f, 1.0f, PIMAX_HANDS_TOUCH_STICK},
	    {"half", 0.51f, 0.51f, 0},
	    {"thumb_btn1", 0.0f, 0.0f, PIMAX_HANDS_TOUCH_BTN1},
	    {"thumb_stick_click", 0.0f, 0.0f, PIMAX_HANDS_TOUCH_STICK | PIMAX_HANDS_CLICK_STICK},
	    {"thumb_menu_grip", 0.0f, 0.8f, PIMAX_HANDS_CLICK_MENU},
	};
	printf("# generated by pimax-re/analysis/tools/gen_hand_golden.c-style harness (see rust/omarchyvr-xrtest/tests/golden/README)\n");
	for (unsigned k = 0; k < sizeof cases / sizeof cases[0]; k++) {
		pimax_hands *h = pimax_hands_create();
		pimax_hands_input in = {.trigger = cases[k].trigger, .grip = cases[k].grip, .flags = cases[k].flags};
		uint64_t t = 1000ull * 1000000;
		for (int i = 0; i < 800; i++) { t += 4000000ull; pimax_hands_update(h, t, &in); }
		pimax_hands_out out;
		pimax_hands_get(h, &out);
		for (int hand = 0; hand < 2; hand++) {
			struct u_hand_tracking_values v; memset(&v, 0, sizeof v);
			to_values(&out, &v);
			struct xrt_space_relation root; memset(&root, 0, sizeof root); root.pose.orientation.w = 1;
			struct xrt_hand_joint_set set; memset(&set, 0, sizeof set);
			u_hand_sim_simulate_generic(&v, hand == 0 ? XRT_HAND_LEFT : XRT_HAND_RIGHT, &root, &set);
			printf("case %s %c in trigger=%.3f grip=%.3f flags=%u curls %.6f %.6f %.6f %.6f %.6f thumb_state=%u\n", cases[k].name,
			       hand == 0 ? 'L' : 'R', cases[k].trigger, cases[k].grip, cases[k].flags, out.curl[0], out.curl[1], out.curl[2],
			       out.curl[3], out.curl[4], out.thumb_state);
			for (int j = 0; j < 26; j++) {
				const struct xrt_pose *p = &set.values.hand_joint_set_default[j].relation.pose;
				printf("%.7f %.7f %.7f %.7f %.7f %.7f %.7f\n", p->position.x, p->position.y, p->position.z, p->orientation.x,
				       p->orientation.y, p->orientation.z, p->orientation.w);
			}
		}
		pimax_hands_destroy(h);
	}
	return 0;
}
