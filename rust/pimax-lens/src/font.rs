fn rows(c: char) -> &'static [&'static str; 7] {
    let c = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .map_or(&BOX, |(_, r)| r)
}

/// True if the pixel (`col` 0..5, `row` 0..7) of the glyph for `c` is set.
pub fn pixel(c: char, col: u32, row: u32) -> bool {
    if col >= GLYPH_W || row >= GLYPH_H {
        return false;
    }
    rows(c)[row as usize].as_bytes()[col as usize] == b'#'
}

/// Size in pixels of `text` drawn at `scale`: one pixel column of spacing between glyphs.
pub fn text_size(text: &str, scale: u32) -> (u32, u32) {
    let n = text.chars().count() as u32;
    if n == 0 {
        return (0, 0);
    }
    ((n * (GLYPH_W + 1) - 1) * scale, GLYPH_H * scale)
}

/// Call `plot(x, y)` for every set pixel of `text` whose top-left corner is at (`x0`, `y0`).
pub fn draw_text<F: FnMut(i32, i32)>(text: &str, x0: i32, y0: i32, scale: u32, mut plot: F) {
    let s = scale as i32;
    for (i, ch) in text.chars().enumerate() {
        let gx = x0 + (i as i32) * (GLYPH_W as i32 + 1) * s;
        for row in 0..GLYPH_H {
            for col in 0..GLYPH_W {
                if pixel(ch, col, row) {
                    for dy in 0..s {
                        for dx in 0..s {
                            plot(gx + col as i32 * s + dx, y0 + row as i32 * s + dy);
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_5_wide_7_tall_and_unique_char() {
        let mut seen = std::collections::HashSet::new();
        for (c, r) in GLYPHS {
            assert!(seen.insert(*c), "duplicate glyph {c:?}");
            assert_eq!(r.len(), 7);
            for row in r.iter() {
                assert_eq!(row.len(), 5, "glyph {c:?}");
                assert!(row.bytes().all(|b| b == b'#' || b == b'.'), "glyph {c:?}");
            }
        }
        for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,:-+=/%()[]_".chars() {
            assert!(seen.contains(&c), "missing {c:?}");
        }
    }

    #[test]
    fn letters_are_distinct_and_non_blank() {
        let sig = |c: char| -> Vec<bool> {
            (0..7)
                .flat_map(|r| (0..5).map(move |k| pixel(c, k, r)))
                .collect()
        };
        let all: Vec<char> = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789".chars().collect();
        for (i, &a) in all.iter().enumerate() {
            assert!(sig(a).iter().any(|&p| p), "{a} blank");
            for &b in &all[i + 1..] {
                assert_ne!(sig(a), sig(b), "{a} and {b} look the same");
            }
        }
    }

    #[test]
    fn lower_case_maps_to_upper_and_unknown_is_a_box() {
        assert_eq!(pixel('a', 1, 0), pixel('A', 1, 0));
        assert!(pixel('\u{263a}', 0, 0) && pixel('\u{263a}', 4, 6) && !pixel('\u{263a}', 2, 3));
        assert!(!pixel('A', 5, 0) && !pixel('A', 0, 7));
    }

    #[test]
    fn size_and_draw() {
        assert_eq!(text_size("", 3), (0, 0));
        assert_eq!(text_size("A", 1), (5, 7));
        assert_eq!(text_size("AB", 2), (22, 14));
        let mut n = 0;
        let (mut maxx, mut maxy) = (0, 0);
        draw_text("1", 10, 20, 2, |x, y| {
            n += 1;
            maxx = maxx.max(x);
            maxy = maxy.max(y);
        });
        let lit = (0..7)
            .flat_map(|r| (0..5).map(move |c| pixel('1', c, r)))
            .filter(|&p| p)
            .count();
        assert_eq!(n, lit * 4);
        assert!(maxx < 10 + 10 && maxy < 20 + 14);
    }
}
